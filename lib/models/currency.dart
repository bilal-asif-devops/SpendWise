  static Currency findByCode(String code, {Currency? fallback}) {
    final upper = code.toUpperCase().trim();
    return currencies.firstWhere(
      (c) => c.code == upper,
      orElse: () => fallback ?? currencies.first,
    );
  }

  static List<Currency> search(String query) {
    if (query.trim().isEmpty) return currencies;
    final q = query.toLowerCase().trim();
    return currencies.where((c) {
      return c.code.toLowerCase().contains(q) ||
          c.name.toLowerCase().contains(q) ||
          c.symbol.toLowerCase().contains(q);
    }).toList();
  }

  static double getEstimatedRate(String fromCode, String toCode) {
    final from = findByCode(fromCode);
    final to = findByCode(toCode);
    if (from.baseRateToUSD <= 0) return 1.0;
    return to.baseRateToUSD / from.baseRateToUSD;
  }
